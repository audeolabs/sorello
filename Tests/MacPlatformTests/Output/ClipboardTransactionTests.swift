/// Putting the text on the clipboard and the previous contents back, against a fake pasteboard and, once, a real
/// pasteboard with a unique name. The user's clipboard is never touched. All text is invented.
@Suite struct ClipboardTransactionTests {
    private let original = [
        PasteboardItemData([
            PasteboardRepresentation(type: "public.utf8-plain-text", data: Data("Copied earlier".utf8)),
            PasteboardRepresentation(type: "public.html", data: Data("<b>Copied earlier</b>".utf8)),
        ]),
        PasteboardItemData([PasteboardRepresentation(type: "com.example.invented", data: Data([1, 2, 3]))]),
    ]

    private func pasteboard(holding items: [PasteboardItemData]) -> FakePasteboard {
        let pasteboard = FakePasteboard(log: EventLog())
        pasteboard.userCopies(items)
        return pasteboard
    }

    private static func plain(_ text: String) -> [PasteboardItemData] {
        [PasteboardItemData([PasteboardRepresentation(type: ClipboardTransaction.textType, data: Data(text.utf8))])]
    }

    private static func transient(_ text: String) -> [PasteboardItemData] {
        [PasteboardItemData([
            PasteboardRepresentation(type: ClipboardTransaction.textType, data: Data(text.utf8)),
            PasteboardRepresentation(type: ClipboardTransaction.transientType, data: Data()),
            PasteboardRepresentation(type: ClipboardTransaction.autoGeneratedType, data: Data()),
        ])]
    }

    @Test func restoresThePreviousContents() throws {
        let pasteboard = pasteboard(holding: original)
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        #expect(transaction.willRestore)
        #expect(pasteboard.items == Self.transient("Invented words"))
        #expect(transaction.restore())
        #expect(pasteboard.items == original)
    }

    @Test func marksTheTextTransientOnlyWhenItWillBeRestored() throws {
        let restoring = pasteboard(holding: original)
        _ = try #require(ClipboardTransaction.write("Invented words", to: restoring, restoring: true))
        #expect(restoring.items == Self.transient("Invented words"))

        let keeping = pasteboard(holding: original)
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: keeping, restoring: false))
        #expect(!transaction.willRestore)
        #expect(keeping.items == Self.plain("Invented words"))
        #expect(!transaction.restore())
        #expect(keeping.items == Self.plain("Invented words"))
    }

    @Test(arguments: ["Something else", "Invented words"])
    func neverOverwritesWhatTheUserCopiedMeanwhile(_ copied: String) throws {
        let pasteboard = pasteboard(holding: original)
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        // Even the very same text copied again is the user's, not ours.
        pasteboard.userCopies(Self.plain(copied))
        #expect(!transaction.restore())
        #expect(pasteboard.items == Self.plain(copied))
    }

    @Test func keepsEveryItemAndTypeIncludingEmptyOnes() throws {
        let items = original + [
            PasteboardItemData([PasteboardRepresentation(type: "com.example.empty", data: Data())]),
            PasteboardItemData([]),
        ]
        let pasteboard = pasteboard(holding: items)
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        #expect(transaction.restore())
        #expect(pasteboard.items == items)
    }

    @Test func restoresAnEmptyClipboardAsEmpty() throws {
        let pasteboard = pasteboard(holding: [])
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        #expect(transaction.willRestore)
        #expect(transaction.restore())
        #expect(pasteboard.items.isEmpty)
    }

    @Test func leavesAClipboardOverTheSizeLimitAlone() throws {
        let limit = ClipboardTransaction.snapshotByteLimit
        let atLimit = pasteboard(holding: [PasteboardItemData([
            PasteboardRepresentation(type: "com.example.big", data: Data(count: limit - 10)),
            PasteboardRepresentation(type: "com.example.small", data: Data(count: 10)),
        ])])
        #expect(try #require(ClipboardTransaction.write("Invented", to: atLimit, restoring: true)).willRestore)

        let overLimit = pasteboard(holding: [
            PasteboardItemData([PasteboardRepresentation(type: "com.example.big", data: Data(count: limit))]),
            PasteboardItemData([PasteboardRepresentation(type: "com.example.small", data: Data(count: 1))]),
        ])
        let transaction = try #require(ClipboardTransaction.write("Invented", to: overLimit, restoring: true))
        #expect(!transaction.willRestore)
        #expect(overLimit.items == Self.plain("Invented"))
    }

    @Test func noRestoreWhenTheCopyIsIncomplete() throws {
        let pasteboard = pasteboard(holding: original)
        pasteboard.update { $0.unreadable = true }
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        #expect(!transaction.willRestore)
        #expect(pasteboard.items == Self.plain("Invented words"))
    }

    @Test func noRestoreWhenThePasteboardChangesDuringTheCopy() throws {
        let pasteboard = pasteboard(holding: original)
        pasteboard.update { state in
            state.onRead = { [pasteboard] in
                pasteboard.update { $0.onRead = nil }
                pasteboard.userCopies(Self.plain("Copied during the read"))
            }
        }
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        #expect(!transaction.willRestore)
        #expect(pasteboard.items == Self.plain("Invented words"))
    }

    @Test func aRefusedWriteIsReportedAndPutBack() {
        let pasteboard = pasteboard(holding: original)
        pasteboard.update { $0.refusedWrite = 1 }
        #expect(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true) == nil)
        #expect(pasteboard.items == original)
    }

    @Test func keepingTheTextForTheUserWritesItPlainly() throws {
        let pasteboard = pasteboard(holding: original)
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        #expect(transaction.keepForUser())
        #expect(pasteboard.items == Self.plain("Invented words"))
        #expect(!transaction.restore(), "Kept text is not taken away again")
        #expect(pasteboard.items == Self.plain("Invented words"))

        // Once the user has copied something else, keeping changes nothing.
        let other = self.pasteboard(holding: original)
        let second = try #require(ClipboardTransaction.write("Invented words", to: other, restoring: true))
        other.userCopies(Self.plain("Something else"))
        #expect(!second.keepForUser())
        #expect(other.items == Self.plain("Something else"))
    }

    /// If the plain copy is refused, the user gets their previous clipboard back rather than an empty one.
    @Test func aRefusedPlainCopyPutsThePreviousClipboardBack() throws {
        let pasteboard = pasteboard(holding: original)
        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        pasteboard.update { $0.refusedWrite = 2 }
        #expect(!transaction.keepForUser())
        #expect(pasteboard.items == original)
    }
}

/// The real pasteboard implementation, on a pasteboard of its own that no other app knows about.
@Suite struct SystemPasteboardTests {
    private static let customType = "com.audeolabs.sorello.tests.invented"

    @Test func roundTripOnAPrivatePasteboard() throws {
        let name = NSPasteboard.Name("com.audeolabs.sorello.tests.\(UUID().uuidString)")
        defer { NSPasteboard(name: name).releaseGlobally() }
        let pasteboard = SystemPasteboard(NSPasteboard(name: name))

        let original = [
            PasteboardItemData([
                PasteboardRepresentation(type: ClipboardTransaction.textType, data: Data("Copied earlier".utf8)),
                PasteboardRepresentation(type: Self.customType, data: Data([7, 8, 9])),
            ]),
            PasteboardItemData([PasteboardRepresentation(type: Self.customType, data: Data([1]))]),
        ]
        let before = pasteboard.clear()
        #expect(pasteboard.write(original))
        #expect(pasteboard.changeCount == before, "Writing to a pasteboard just cleared does not change its count")
        #expect(pasteboard.readItems(byteLimit: .max) == .items(original))
        #expect(pasteboard.readItems(byteLimit: 3) == .overLimit)

        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        #expect(transaction.willRestore)
        let written = NSPasteboard(name: name)
        #expect(written.string(forType: .string) == "Invented words")
        #expect(written.types?.contains(NSPasteboard.PasteboardType(ClipboardTransaction.transientType)) == true)
        #expect(transaction.restore())
        #expect(pasteboard.readItems(byteLimit: .max) == .items(original))
    }

    @Test func doesNotRestoreOverAnotherWriter() throws {
        let name = NSPasteboard.Name("com.audeolabs.sorello.tests.\(UUID().uuidString)")
        defer { NSPasteboard(name: name).releaseGlobally() }
        let pasteboard = SystemPasteboard(NSPasteboard(name: name))
        _ = pasteboard.clear()
        #expect(pasteboard.write([PasteboardItemData([
            PasteboardRepresentation(type: ClipboardTransaction.textType, data: Data("Copied earlier".utf8)),
        ])]))

        let transaction = try #require(ClipboardTransaction.write("Invented words", to: pasteboard, restoring: true))
        let other = NSPasteboard(name: name)
        other.clearContents()
        other.setString("Invented words", forType: .string)
        #expect(!transaction.restore())
        #expect(other.string(forType: .string) == "Invented words")
    }
}
