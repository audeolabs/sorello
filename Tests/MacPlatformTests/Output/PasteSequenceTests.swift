import DictationCore
import Foundation
import MacPlatform
import Testing

/// A screen note pasted as a sequence of pieces (ARCHITECTURE.md, section 14, "Pasting a note"), with the inserter's
/// fake pasteboard, keys and manual clock. The text and the image bytes are invented.
@Suite struct PasteSequenceTests {
    static let image = Data([0x89, 0x50, 0x4E, 0x47])
    static let pieces: [PastePiece] = [.text("One"), .png(image), .text("Two")]

    static func transientImage(_ data: Data) -> [PasteboardItemData] {
        [PasteboardItemData([
            PasteboardRepresentation(type: ClipboardTransaction.pngType, data: data),
            PasteboardRepresentation(type: ClipboardTransaction.transientType, data: Data()),
            PasteboardRepresentation(type: ClipboardTransaction.autoGeneratedType, data: Data()),
        ])]
    }

    static func paste(at time: TimeInterval) -> OutputEvent {
        .post(key: KeyCode.ansiV, modifiers: .command, at: time)
    }

    func start(_ h: Harness, _ pieces: [PastePiece] = Self.pieces, restoring: Bool = true)
        -> Task<PasteSequenceOutcome, Never> {
        let inserter = h.inserter
        return Task { await inserter.pasteSequence(pieces, restoring: restoring) }
    }

    /// Lets the clock run until the sequence has put the clipboard back, however it ended.
    func settle(_ h: Harness) async {
        let inserter = h.inserter
        _ = await drive(Task { await inserter.waitUntilIdle() }, clock: h.clock)
    }

    @Test func pastesEachPieceInOrderWaitingAfterEachThenPutsTheClipboardBack() async {
        let h = Harness()
        let outcome = await drive(start(h), clock: h.clock)
        #expect(outcome == .pasted)
        let afterText = PasteboardInserter.textPieceDelay, afterImage = PasteboardInserter.imagePieceDelay
        #expect(h.log.all == [
            .snapshotRead, .clear, .write(PasteboardInserterTests.transient("One")), Self.paste(at: 0),
            .clear, .write(Self.transientImage(Self.image)), Self.paste(at: afterText),
            .clear, .write(PasteboardInserterTests.transient("Two")), Self.paste(at: afterText + afterImage),
        ])
        let last = afterText + afterImage
        #expect(await h.clock.nextDeadline() == last + PasteboardInserter.restoreDelay)
        h.clock.advance(to: last + PasteboardInserter.restoreDelay)
        await h.idle()
        #expect(h.pasteboard.items == PasteboardInserterTests.original)
    }

    @Test func withoutRestoringTheLastPieceStaysPlainly() async {
        let h = Harness()
        #expect(await drive(start(h, [.text("One"), .text("Two")], restoring: false), clock: h.clock) == .pasted)
        await settle(h)
        #expect(!h.log.all.contains(.snapshotRead))
        #expect(h.pasteboard.items == PasteboardInserterTests.plain("Two"))
    }

    @Test func stopsWhenTheAppInFrontChangesAndPutsTheClipboardBack() async {
        let h = Harness()
        let frontmost = h.frontmost
        h.keys.update { state in state.onPost = { _ in frontmost.pid.withLock { pid in pid = 999 } } }
        let outcome = await drive(start(h), clock: h.clock)
        #expect(outcome == .stopped(pasted: 1, why: .blocked(.targetChanged)))
        #expect(h.log.posts == [Self.paste(at: 0)])
        await settle(h)
        #expect(h.pasteboard.items == PasteboardInserterTests.original)
    }

    @Test func stopsWhenSomeoneElseWritesTheClipboardAndLeavesTheirCopy() async {
        let h = Harness()
        let pasteboard = h.pasteboard
        let theirs = PasteboardInserterTests.plain("Copied meanwhile")
        h.keys.update { $0.onPost = { _ in pasteboard.userCopies(theirs) } }
        let outcome = await drive(start(h), clock: h.clock)
        #expect(outcome == .stopped(pasted: 1, why: .clipboardChanged))
        await settle(h)
        #expect(h.log.posts.count == 1)
        #expect(h.pasteboard.items == theirs)
    }

    @Test func pastesNothingWithoutAccessibility() async {
        let h = Harness()
        h.keys.update { $0.mayPost = false }
        let outcome = await drive(start(h), clock: h.clock)
        #expect(outcome == .stopped(pasted: 0, why: .blocked(.accessibilityMissing)))
        await settle(h)
        #expect(h.log.all.isEmpty)
        #expect(h.pasteboard.items == PasteboardInserterTests.original)
    }

    @Test func waitsForTheShortcutsModifiersToComeUp() async {
        let h = Harness()
        h.keys.update { $0.modifiers = [.option, .shift] }
        let task = start(h)
        #expect(await h.clock.nextDeadline() == PasteboardInserter.modifierPollInterval)
        h.keys.update { $0.modifiers = [] }
        h.clock.advance(to: PasteboardInserter.modifierPollInterval)
        #expect(await drive(task, clock: h.clock) == .pasted)
        #expect(h.log.posts.first == Self.paste(at: PasteboardInserter.modifierPollInterval))
    }

    @Test func aCancelledSequenceStopsBeforeTheNextPieceAndPutsTheClipboardBack() async {
        let h = Harness()
        let task = start(h)
        _ = await h.clock.nextDeadline()
        task.cancel()
        let outcome = await drive(task, clock: h.clock)
        #expect(outcome == .stopped(pasted: 1, why: .cancelled))
        await settle(h)
        #expect(h.log.posts == [Self.paste(at: 0)])
        #expect(h.pasteboard.items == PasteboardInserterTests.original)
    }

    @Test func holdsTheClipboardTurnSoADictationWaitsForTheWholeSequence() async {
        let h = Harness()
        let sequence = start(h)
        _ = await h.clock.nextDeadline()
        let dictation = h.insert(ComposedInsertion(text: "Later"))
        let outcome = await drive(sequence, clock: h.clock)
        #expect(outcome == .pasted)
        #expect(await drive(dictation, clock: h.clock) == .inserted)
        let writes = h.log.pasteboardEvents.compactMap { event -> [PasteboardItemData]? in
            if case .write(let items) = event { items } else { nil }
        }
        #expect(writes.firstIndex(of: PasteboardInserterTests.transient("Later"))
            ?? 0 > writes.firstIndex(of: PasteboardInserterTests.original) ?? Int.max,
            "the dictation is written after the sequence put the clipboard back")
    }
}
