import Testing

/// One insertion transaction (ARCHITECTURE.md, section 6, "Text insertion"), with a fake pasteboard, fake keys, a
/// fake field and a manual clock. No real key is posted and the user's clipboard is never touched. All text is
/// invented.
@Suite struct PasteboardInserterTests {
    static let original = [PasteboardItemData([
        PasteboardRepresentation(type: ClipboardTransaction.textType, data: Data("Copied earlier".utf8)),
        PasteboardRepresentation(type: "com.example.invented", data: Data([4, 2])),
    ])]
    static let words = "Invented words."
    static let context = InsertionContext(before: "Some", after: " invented text")
    static let preparedField = SeenField(pid: FakeTextField.pid, element: 1,
                                         selection: TextFieldRange(location: 4, length: 0))
    static let paste = OutputEvent.post(key: KeyCode.ansiV, modifiers: .command, at: 0)

    static func plain(_ text: String) -> [PasteboardItemData] {
        [PasteboardItemData([PasteboardRepresentation(type: ClipboardTransaction.textType, data: Data(text.utf8))])]
    }

    static func transient(_ text: String) -> [PasteboardItemData] {
        [PasteboardItemData([
            PasteboardRepresentation(type: ClipboardTransaction.textType, data: Data(text.utf8)),
            PasteboardRepresentation(type: ClipboardTransaction.transientType, data: Data()),
            PasteboardRepresentation(type: ClipboardTransaction.autoGeneratedType, data: Data()),
        ])]
    }

    static func returnKey(at time: TimeInterval) -> OutputEvent {
        .post(key: KeyCode.returnKey, modifiers: [], at: time)
    }

    // MARK: - The whole transaction

    @Test func pastesThenPressesReturnThenRestoresInOrderAndOnTime() async {
        let h = Harness()
        h.pasteMovesTheCaret()
        let outcome = await h.run(ComposedInsertion(text: Self.words, pressEnter: true))
        #expect(outcome == .inserted)
        #expect(h.log.all == [
            .compose(.cursor(Self.context, Self.preparedField)),
            .snapshotRead, .clear, .write(Self.transient(Self.words)),
            Self.paste,
        ])

        // Return 80 ms after the paste, although the paste moved the selection.
        #expect(await h.clock.nextDeadline() == PasteboardInserter.returnDelay)
        h.clock.advance(to: PasteboardInserter.returnDelay)
        // The previous clipboard 1 s after the paste.
        #expect(await h.clock.nextDeadline() == PasteboardInserter.restoreDelay)
        #expect(h.log.posts == [Self.paste, Self.returnKey(at: PasteboardInserter.returnDelay)])
        h.clock.advance(to: PasteboardInserter.restoreDelay)
        await h.idle()
        #expect(Array(h.log.all.suffix(3)) == [
            Self.returnKey(at: PasteboardInserter.returnDelay), .clear, .write(Self.original),
        ])
        #expect(h.pasteboard.items == Self.original)
    }

    @Test func withoutRestoringTheTextIsWrittenPlainlyAndStays() async {
        let h = Harness()
        #expect(await h.run(ComposedInsertion(text: Self.words), restore: false) == .inserted)
        await h.idle()
        #expect(h.log.all == [.compose(.cursor(Self.context, Self.preparedField)),
                              .clear, .write(Self.plain(Self.words)), Self.paste])
        #expect(h.pasteboard.items == Self.plain(Self.words))
    }

    @Test func pastesWithTheKeyTheLayoutGives() async {
        let h = Harness(pasteKey: 47)
        #expect(await h.run(ComposedInsertion(text: Self.words)) == .inserted)
        #expect(h.log.posts == [.post(key: 47, modifiers: .command, at: 0)])
    }

    // MARK: - Step 1: modifiers

    @Test func waitsForModifiersToComeUp() async {
        let h = Harness()
        h.keys.update { $0.modifiers = [.command] }
        let task = h.insert(ComposedInsertion(text: Self.words))
        #expect(await h.clock.nextDeadline() == 0.01)
        h.clock.advance(to: 0.01)
        #expect(await h.clock.nextDeadline() == 0.02)
        h.keys.update { $0.modifiers = [] }
        h.clock.advance(to: 0.02)
        #expect(await finished(task) == .inserted)
        #expect(h.log.posts == [.post(key: KeyCode.ansiV, modifiers: .command, at: 0.02)])
    }

    @Test func fnAloneIsNotWaitedFor() async {
        let h = Harness()
        h.keys.update { $0.modifiers = [.function] }
        #expect(await h.run(ComposedInsertion(text: Self.words)) == .inserted)
        #expect(h.log.posts == [Self.paste])
    }

    @Test func givesUpOnModifiersAfterOneSecond() async {
        let h = Harness()
        h.keys.update { $0.modifiers = [.shift] }
        let outcome = await drive(h.insert(ComposedInsertion(text: Self.words)), clock: h.clock)
        #expect(outcome == .leftOnClipboard(.modifiersStillDown))
        #expect(abs(h.clock.now - PasteboardInserter.modifierWaitLimit) < 1e-6)
        #expect(h.log.all == [.compose(.clipboard(.modifiersStillDown)), .clear, .write(Self.plain(Self.words))])
        #expect(h.field.state.withLock { $0.captureCalls } == 0)
    }

    // MARK: - Step 2 and 3: clipboard only

    enum Blocker: String, CaseIterable, Sendable {
        case locked, noAccessibility, modifierHeld

        var reason: ClipboardReason {
            switch self {
            case .locked: .screenLocked
            case .noAccessibility: .accessibilityMissing
            case .modifierHeld: .modifiersStillDown
            }
        }

        func apply(to h: Harness) {
            switch self {
            case .locked: h.session.available.withLock { $0 = false }
            case .noAccessibility:
                h.keys.update { $0.mayPost = false }
                h.field.update { $0.trusted = false }
            case .modifierHeld: h.keys.update { $0.modifiers = [.option] }
            }
        }
    }

    @Test(arguments: Blocker.allCases)
    func clipboardOnlyComposesOnceWithTheReasonAndReadsNoField(_ blocker: Blocker) async {
        let h = Harness()
        blocker.apply(to: h)
        let outcome = await drive(h.insert(ComposedInsertion(text: Self.words, pressEnter: true)), clock: h.clock)
        await h.idle()
        #expect(outcome == .leftOnClipboard(blocker.reason))
        #expect(h.log.all == [.compose(.clipboard(blocker.reason)), .clear, .write(Self.plain(Self.words))])
        #expect(h.field.state.withLock { $0.captureCalls } == 0)
        #expect(h.pasteboard.items == Self.plain(Self.words))
    }

    @Test(arguments: Blocker.allCases)
    func returnAloneToTheClipboardIsNotPostedAndWritesNothing(_ blocker: Blocker) async {
        let h = Harness()
        blocker.apply(to: h)
        let outcome = await drive(h.insert(ComposedInsertion(text: "", pressEnter: true)), clock: h.clock)
        #expect(outcome == .failed(.commandNotPosted))
        #expect(h.log.all == [.compose(.clipboard(blocker.reason))])
        #expect(h.pasteboard.items == Self.original)
    }

    @Test func nothingToInsertTouchesNothing() async {
        let h = Harness()
        #expect(await h.run(ComposedInsertion(text: "")) == .nothingToInsert)
        #expect(h.log.all == [.compose(.cursor(Self.context, Self.preparedField))])
    }

    @Test(arguments: ["secure", "failing"])
    func anUnreadableFieldStillGetsThePaste(_ condition: String) async {
        let h = Harness()
        h.field.update { state in
            if condition == "secure" { state.secure = true } else { state.failReads = true }
        }
        #expect(await h.run(ComposedInsertion(text: Self.words)) == .inserted)
        #expect(h.log.all.first == .compose(.cursor(nil, nil)))
        #expect(h.log.posts == [Self.paste])
    }

    @Test func anUnreadableFieldStillNeedsTheSameApp() async {
        let h = Harness()
        h.field.update { $0.secure = true }
        let outcome = await h.run(ComposedInsertion(text: Self.words)) { h.frontmost.pid.withLock { $0 = 999 } }
        #expect(outcome == .leftOnClipboard(.targetChanged))
        #expect(h.log.posts.isEmpty)
    }

    // MARK: - Step 4: checks after compose

    enum Change: String, CaseIterable, Sendable {
        case appSwitched, focusMovedInTheSameApp, selectionMoved, locked, accessibilityRevoked, modifierPressed

        var reason: ClipboardReason {
            switch self {
            case .appSwitched, .focusMovedInTheSameApp, .selectionMoved: .targetChanged
            case .locked: .screenLocked
            case .accessibilityRevoked: .accessibilityMissing
            case .modifierPressed: .modifiersStillDown
            }
        }

        func apply(to h: Harness) {
            switch self {
            case .appSwitched: h.frontmost.pid.withLock { $0 = 999 }
            // The prepared field keeps its selection, but another field of the same app has focus.
            case .focusMovedInTheSameApp: h.field.update { $0.focusedElement = 2 }
            case .selectionMoved: h.field.update { $0.caret = 7 }
            case .locked: h.session.available.withLock { $0 = false }
            case .accessibilityRevoked:
                h.keys.update { $0.mayPost = false }
                h.field.update { $0.trusted = false }
            case .modifierPressed: h.keys.update { $0.modifiers = [.control] }
            }
        }
    }

    @Test(arguments: Change.allCases)
    func aChangeWhileComposingLeavesTheTextOnTheClipboard(_ change: Change) async {
        let h = Harness()
        let outcome = await h.run(ComposedInsertion(text: Self.words, pressEnter: true)) { change.apply(to: h) }
        await h.idle()
        #expect(outcome == .leftOnClipboard(change.reason))
        #expect(h.log.composeCount == 1)
        #expect(h.log.posts.isEmpty)
        // Left for the user: written plainly in the end, and not put back.
        #expect(h.pasteboard.items == Self.plain(Self.words))
    }

    @Test(arguments: Change.allCases)
    func aChangeWhileComposingBlocksReturnAlone(_ change: Change) async {
        let h = Harness()
        let outcome = await h.run(ComposedInsertion(text: "", pressEnter: true)) { change.apply(to: h) }
        #expect(outcome == .failed(.commandNotPosted))
        #expect(h.log.posts.isEmpty)
        #expect(h.log.pasteboardEvents.isEmpty)
        #expect(h.pasteboard.items == Self.original)
    }

    // MARK: - Step 6: Return

    @Test func returnAloneIsPostedAtOnceAndLeavesTheClipboard() async {
        let h = Harness()
        #expect(await h.run(ComposedInsertion(text: "", pressEnter: true)) == .inserted)
        await h.idle()
        #expect(h.log.all == [.compose(.cursor(Self.context, Self.preparedField)), Self.returnKey(at: 0)])
        #expect(h.pasteboard.items == Self.original)
    }

    enum AfterPaste: String, CaseIterable, Sendable {
        case appSwitched, focusMovedInTheSameApp, locked, accessibilityRevoked, modifierPressed

        func apply(to h: Harness) {
            switch self {
            case .appSwitched: h.frontmost.pid.withLock { $0 = 999 }
            case .focusMovedInTheSameApp: h.field.update { $0.focusedElement = 2 }
            case .locked: h.session.available.withLock { $0 = false }
            case .accessibilityRevoked:
                h.keys.update { $0.mayPost = false }
                h.field.update { $0.trusted = false }
            case .modifierPressed: h.keys.update { $0.modifiers = [.command] }
            }
        }
    }

    @Test(arguments: AfterPaste.allCases)
    func returnIsSkippedWhenTheTargetChangesAfterThePaste(_ change: AfterPaste) async {
        let h = Harness()
        h.keys.update { state in
            state.onPost = { _ in
                h.keys.update { $0.onPost = nil }
                change.apply(to: h)
            }
        }
        #expect(await h.run(ComposedInsertion(text: Self.words, pressEnter: true)) == .inserted)
        #expect(await h.clock.nextDeadline() == PasteboardInserter.returnDelay)
        h.clock.advance(to: PasteboardInserter.returnDelay)
        // The restore is still due, and nothing is tried again.
        #expect(await h.clock.nextDeadline() == PasteboardInserter.restoreDelay)
        h.clock.advance(to: PasteboardInserter.restoreDelay)
        await h.idle()
        #expect(h.log.posts == [Self.paste])
        #expect(h.pasteboard.items == Self.original)
    }

    // MARK: - Failures

    @Test func aPasteboardThatRefusesTheTextPostsNothing() async {
        let h = Harness()
        h.pasteboard.update { $0.refuseWrites = true }
        #expect(await h.run(ComposedInsertion(text: Self.words)) == .failed(.pasteboardUnavailable))
        #expect(h.log.posts.isEmpty)
    }

    @Test func eventsThatCannotBeMadeFailAndPutTheClipboardBack() async {
        let h = Harness()
        h.keys.update { $0.refusePosting = true }
        #expect(await h.run(ComposedInsertion(text: Self.words, pressEnter: true)) == .failed(.eventPostFailed))
        await h.idle()
        #expect(h.pasteboard.items == Self.original)

        #expect(await h.run(ComposedInsertion(text: "", pressEnter: true)) == .failed(.commandNotPosted))
    }

    // MARK: - One at a time

    @Test func theNextTransactionWaitsForThePreviousRestore() async throws {
        let h = Harness()
        #expect(await h.run(ComposedInsertion(text: "First invented words.")) == .inserted)
        let second = h.insert(ComposedInsertion(text: "Second invented words."))
        #expect(await h.clock.nextDeadline() == PasteboardInserter.restoreDelay)
        h.clock.advance(to: PasteboardInserter.restoreDelay)
        #expect(await finished(second) == .inserted)
        let events = h.log.all
        let restored = try #require(events.firstIndex(of: .write(Self.original)))
        let secondCompose = try #require(events.lastIndex { if case .compose = $0 { true } else { false } })
        #expect(restored < secondCompose)
        // The second transaction copied the clipboard the first one put back.
        #expect(Array(events.suffix(4)) == [
            .snapshotRead, .clear, .write(Self.transient("Second invented words.")),
            .post(key: KeyCode.ansiV, modifiers: .command, at: PasteboardInserter.restoreDelay),
        ])
    }

    // MARK: - Cancellation

    @Test func cancelledWhileWaitingForModifiers() async {
        let h = Harness()
        h.keys.update { $0.modifiers = [.command] }
        let task = h.insert(ComposedInsertion(text: Self.words))
        _ = await h.clock.nextDeadline()
        task.cancel()
        #expect(await finished(task) == .failed(.cancelled))
        await h.idle()
        #expect(h.log.all.isEmpty)
    }

    @Test func cancelledBeforeTheWrite() async {
        let h = Harness()
        let outcome = await h.run(ComposedInsertion(text: Self.words)) { cancelCurrentTask() }
        await h.idle()
        #expect(outcome == .failed(.cancelled))
        #expect(h.log.all == [.compose(.cursor(Self.context, Self.preparedField))])
        #expect(h.pasteboard.items == Self.original)
    }

    @Test func cancelledAfterTheWritePutsTheClipboardBack() async {
        let h = Harness()
        h.cancelOnFirstWrite()
        #expect(await h.run(ComposedInsertion(text: Self.words, pressEnter: true)) == .failed(.cancelled))
        await h.idle()
        #expect(h.log.posts.isEmpty)
        #expect(h.pasteboard.items == Self.original)
    }

    @Test func cancelledAfterTheWriteWithoutASnapshotLeavesTheClipboardAlone() async {
        let h = Harness()
        h.cancelOnFirstWrite()
        let outcome = await h.run(ComposedInsertion(text: Self.words), restore: false)
        await h.idle()
        #expect(outcome == .failed(.cancelled))
        #expect(h.log.pasteboardEvents == [.clear, .write(Self.plain(Self.words))])
        #expect(h.log.posts.isEmpty)
    }

    @Test func cancelledAfterTheWriteKeepsWhatTheUserCopiedMeanwhile() async {
        let h = Harness()
        h.pasteboard.update { state in
            state.onWrite = {
                h.pasteboard.update { $0.onWrite = nil }
                h.pasteboard.userCopies(Self.plain("Copied meanwhile"))
                cancelCurrentTask()
            }
        }
        #expect(await h.run(ComposedInsertion(text: Self.words)) == .failed(.cancelled))
        await h.idle()
        #expect(Array(h.log.all.dropFirst()) == [.snapshotRead, .clear, .write(Self.transient(Self.words)), .userCopy])
        #expect(h.pasteboard.items == Self.plain("Copied meanwhile"))
    }

    @Test func cancelledAfterThePasteChangesNothing() async {
        let h = Harness()
        h.keys.update { state in
            state.onPost = { _ in
                h.keys.update { $0.onPost = nil }
                cancelCurrentTask()
            }
        }
        #expect(await h.run(ComposedInsertion(text: Self.words, pressEnter: true)) == .inserted)
        #expect(await h.clock.nextDeadline() == PasteboardInserter.returnDelay)
        h.clock.advance(to: PasteboardInserter.returnDelay)
        #expect(await h.clock.nextDeadline() == PasteboardInserter.restoreDelay)
        h.clock.advance(to: PasteboardInserter.restoreDelay)
        await h.idle()
        #expect(h.log.posts == [Self.paste, Self.returnKey(at: PasteboardInserter.returnDelay)])
        #expect(h.pasteboard.items == Self.original)
    }

    @Test func cancelledWhileWaitingForThePreviousTransaction() async {
        let h = Harness()
        #expect(await h.run(ComposedInsertion(text: "First invented words.")) == .inserted)
        let second = h.insert(ComposedInsertion(text: "Second invented words."))
        second.cancel()
        #expect(await finished(second) == .failed(.cancelled))
        #expect(h.log.composeCount == 1)

        #expect(await h.clock.nextDeadline() == PasteboardInserter.restoreDelay)
        h.clock.advance(to: PasteboardInserter.restoreDelay)
        await h.idle()
        #expect(h.pasteboard.items == Self.original)
        #expect(await h.run(ComposedInsertion(text: "Third invented words."), restore: false) == .inserted)
    }
}

/// The inserter wired to fakes.
struct Harness: Sendable {
    let log: EventLog
    let clock: ManualClock
    let pasteboard: FakePasteboard
    let keys: FakeKeys
    let field: FakeTextField
    let session = FakeSession()
    let frontmost = FakeFrontmost()
    let inserter: PasteboardInserter

    init(pasteKey: UInt16 = KeyCode.ansiV) {
        let log = EventLog()
        let clock = ManualClock()
        let field = FakeTextField("Some invented text")
        field.update { $0.caret = 4 }
        self.log = log
        self.clock = clock
        self.field = field
        pasteboard = FakePasteboard(log: log)
        keys = FakeKeys(log: log, clock: clock)
        // The probe's deadline has a clock of its own that never moves, so a fast fake field always wins the race.
        inserter = PasteboardInserter(pasteboard: pasteboard, keys: keys,
                                      probe: InsertionContextProbe(reader: field, clock: ManualClock()),
                                      session: session, frontmost: frontmost, pasteKey: { pasteKey }, clock: clock)
        pasteboard.userCopies(PasteboardInserterTests.original)
        log.clear()
    }

    /// Starts an insertion whose `compose` records the destination, runs `during` as if time passed while it was
    /// suspended, and returns `composed`.
    func insert(_ composed: ComposedInsertion, restore: Bool = true,
                during: @escaping @Sendable () -> Void = {}) -> Task<InsertionOutcome, Never> {
        let log = log
        let inserter = inserter
        return Task {
            await inserter.insert(restoreClipboard: restore) { destination in
                log.append(.compose(SeenDestination(destination)))
                during()
                return composed
            }
        }
    }

    /// Runs an insertion to its outcome, which `insert` returns once the outcome of posting is known.
    func run(_ composed: ComposedInsertion, restore: Bool = true, during: @escaping @Sendable () -> Void = {},
             sourceLocation: SourceLocation = #_sourceLocation) async -> InsertionOutcome? {
        await finished(insert(composed, restore: restore, during: during), sourceLocation: sourceLocation)
    }

    /// Waits until every transaction, with its Return and restore, has finished, without moving the clock. Records
    /// an issue instead of hanging if one is still waiting.
    func idle(sourceLocation: SourceLocation = #_sourceLocation) async {
        let inserter = inserter
        _ = await finished(Task { await inserter.waitUntilIdle() }, sourceLocation: sourceLocation)
    }

    /// The paste lands in the fake field, moving its caret, as a real paste would.
    func pasteMovesTheCaret() {
        let field = field
        keys.update { state in
            state.onPost = { key in
                if key == KeyCode.ansiV { field.paste(PasteboardInserterTests.words) }
            }
        }
    }

    /// The caller's task is cancelled just after the text is written, before any key is posted.
    func cancelOnFirstWrite() {
        let pasteboard = pasteboard
        pasteboard.update { state in
            state.onWrite = {
                pasteboard.update { $0.onWrite = nil }
                cancelCurrentTask()
            }
        }
    }
}
