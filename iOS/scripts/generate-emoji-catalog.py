#!/usr/bin/env python3
"""Writes KeyboardCore/EmojiCatalog.swift and KeyboardCore/EmojiNames.swift from Unicode's data.

Usage: python3 -I scripts/generate-emoji-catalog.py EMOJI_TEST ANNOTATIONS ANNOTATIONS_DERIVED OUTPUT_DIR

  EMOJI_TEST           emoji-test.txt, https://www.unicode.org/Public/emoji/15.0/emoji-test.txt
  ANNOTATIONS          CLDR's common/annotations/en.xml (release-49, https://github.com/unicode-org/cldr)
  ANNOTATIONS_DERIVED  CLDR's common/annotationsDerived/en.xml, same release
  OUTPUT_DIR           KeyboardCore

The catalog keeps every fully-qualified emoji in Unicode's order, by group, without skin-tone variants (the keyboard has
no skin-tone picker yet) and without the Component group. The names give each catalog emoji the words of its English
name and of its keywords, folded to lowercase a-z and digits, for emoji search (ARCHITECTURE.md, "Emoji search"); the
script stops if a catalog emoji has no name. Only the generated Swift files are committed; the data's licence is in
ThirdPartyNotices.md.
"""
import os
import re
import sys
import unicodedata
import xml.etree.ElementTree as ET

GROUPS = [
    ("Smileys & Emotion", "smileys", "face.smiling"),
    ("People & Body", "people", "hand.raised"),
    ("Animals & Nature", "nature", "leaf"),
    ("Food & Drink", "food", "fork.knife"),
    ("Travel & Places", "travel", "car"),
    ("Activities", "activities", "soccerball"),
    ("Objects", "objects", "lightbulb"),
    ("Symbols", "symbols", "heart"),
    ("Flags", "flags", "flag"),
]
SKIN_TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
CLDR_RELEASE = "49"


def read_catalog(path):
    version = "?"
    group = None
    emoji = {name: [] for name, _, _ in GROUPS}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("# Version:"):
                version = line.split(":", 1)[1].strip()
            if line.startswith("# group:"):
                group = line.split(":", 1)[1].strip()
                continue
            if not line.strip() or line.startswith("#") or group not in emoji:
                continue
            codes, rest = line.split(";", 1)
            if rest.split("#", 1)[0].strip() != "fully-qualified":
                continue
            points = [int(code, 16) for code in codes.split()]
            if SKIN_TONES.intersection(points):
                continue
            emoji[group].append("".join(chr(p) for p in points))
    return version, emoji


def write_catalog(out, version, emoji):
    out.write("// Generated by scripts/generate-emoji-catalog.py from Unicode emoji-test.txt, version %s. Do not edit.\n\n" % version)
    out.write("import Foundation\n\n")
    out.write("/// The emoji panel's categories, in Unicode's order: fully-qualified emoji without skin-tone variants.\n")
    out.write("/// Each category is one space-separated string, split only when the panel shows it.\n")
    out.write("enum EmojiCatalog {\n")
    out.write("    struct Category: Equatable, Sendable {\n")
    out.write("        var id: String\n        var name: String\n        /// The SF Symbol of its jump-bar button.\n        var symbol: String\n")
    out.write("        var packed: String\n\n")
    out.write("        var emoji: [String] { packed.split(separator: \" \").map(String.init) }\n    }\n\n")
    out.write("    static let categories: [Category] = [\n")
    for name, ident, symbol in GROUPS:
        packed = " ".join(emoji[name])
        out.write("        Category(id: %s, name: %s, symbol: %s,\n" % (swift(ident), swift(name), swift(symbol)))
        out.write("                 packed: %s),\n" % swift(packed))
    out.write("    ]\n}\n")


def read_annotations(paths):
    """CLDR's names (type="tts") and keywords, by code points without emoji presentation selectors."""
    names, keywords = {}, {}
    for path in paths:
        for annotation in ET.parse(path).getroot().iter("annotation"):
            key = annotation.get("cp").replace("️", "")
            text = annotation.text or ""
            if annotation.get("type") == "tts":
                names[key] = text
            else:
                keywords[key] = text.split("|")
    return names, keywords


def words(text):
    """Lowercase a-z and digit runs, accents removed: "piñata" -> ["pinata"], "o’clock" -> ["o", "clock"]."""
    decomposed = unicodedata.normalize("NFKD", text.lower())
    plain = "".join(c for c in decomposed if not unicodedata.combining(c))
    return [w for w in re.split(r"[^a-z0-9]+", plain) if w]


def write_names(out, version, emoji, names, keywords):
    lines = []
    for group, _, _ in GROUPS:
        for item in emoji[group]:
            key = item.replace("️", "")
            if key not in names:
                sys.exit("no CLDR name for %s (%s)" % (item, " ".join("%04X" % ord(c) for c in item)))
            name = words(names[key])
            extra = []
            for phrase in keywords.get(key, []):
                for word in words(phrase):
                    if word not in name and word not in extra:
                        extra.append(word)
            lines.append("%s;%s;%s" % (item, " ".join(name), " ".join(extra)))
    out.write("// Generated by scripts/generate-emoji-catalog.py from Unicode emoji-test.txt, version %s, and CLDR's English\n" % version)
    out.write("// annotations, release %s (common/annotations/en.xml and common/annotationsDerived/en.xml). Do not edit.\n\n" % CLDR_RELEASE)
    out.write("import Foundation\n\n")
    out.write("/// Emoji search's data (ARCHITECTURE.md, \"Emoji search\"): one line per catalog emoji, in the catalog's order,\n")
    out.write("/// \"emoji;name;keywords\": the words of its English name, then the other words of its keywords, each folded to\n")
    out.write("/// lowercase a-z and digits and separated by spaces. Parsed on the first search.\n")
    out.write("enum EmojiNames {\n")
    out.write("    static let packed = #\"\"\"\n")
    for line in lines:
        out.write(line + "\n")
    out.write("\"\"\"#\n}\n")


def swift(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(emoji_test, annotations, derived, output):
    version, emoji = read_catalog(emoji_test)
    # The base annotations win over derived ones for the same emoji.
    names, keywords = read_annotations([derived, annotations])
    with open(os.path.join(output, "EmojiCatalog.swift"), "w", encoding="utf-8") as out:
        write_catalog(out, version, emoji)
    with open(os.path.join(output, "EmojiNames.swift"), "w", encoding="utf-8") as out:
        write_names(out, version, emoji, names, keywords)


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    main(*sys.argv[1:])
