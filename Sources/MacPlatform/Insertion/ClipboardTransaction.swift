import Foundation

/// Puts a dictation's text on the clipboard and, when asked, puts back what was there before (ARCHITECTURE.md,
/// section 6, "Text insertion", steps 5 and 7).
///
/// Pasteboard access across apps cannot be made atomic, so the change count guards everything: the copy is taken
/// only if nothing changed while it was read, and it is put back only if the pasteboard still holds exactly what
/// this transaction wrote. Something the user copies in the meantime, even the very same text, changes the count
/// and is never overwritten. The copy lives in memory only, for about a second.
public struct ClipboardTransaction: Sendable {
    /// The largest clipboard, in bytes of data, that is copied to be put back. A larger one is left alone.
    public static let snapshotByteLimit = 32 * 1024 * 1024
    /// The type the text is written as.
    public static let textType = "public.utf8-plain-text"
    /// The nspasteboard.org marker for data that is on the clipboard only briefly; clipboard managers skip it.
    public static let transientType = "org.nspasteboard.TransientType"
    /// The nspasteboard.org marker for data an app put there rather than the user.
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    private let pasteboard: any PasteboardAccess
    private let text: String
    /// What to put back; nil when nothing will be.
    private let snapshot: [PasteboardItemData]?
    /// The change count this transaction's write produced.
    private let ownChangeCount: Int

    /// Whether the previous contents were copied in full and will be put back by `restore()`. When true the text was
    /// marked transient; when false it was written plainly.
    public var willRestore: Bool { snapshot != nil }

    private init(pasteboard: any PasteboardAccess, text: String, snapshot: [PasteboardItemData]?, ownChangeCount: Int) {
        self.pasteboard = pasteboard
        self.text = text
        self.snapshot = snapshot
        self.ownChangeCount = ownChangeCount
    }

    /// Writes `text` to `pasteboard`. With `restoring`, the current contents are copied first and the text is marked
    /// transient, unless the copy could not be taken in full, passed the size limit, or the pasteboard changed while
    /// it was read; then nothing will be put back and the text is written plainly.
    ///
    /// Returns nil when the system refused the write. Anything this cleared is put back first, under the same
    /// guards as `restore()`.
    public static func write(_ text: String, to pasteboard: any PasteboardAccess, restoring: Bool) -> ClipboardTransaction? {
        let snapshot = restoring ? takeSnapshot(of: pasteboard) : nil
        let ownChangeCount = pasteboard.clear()
        let transaction = ClipboardTransaction(pasteboard: pasteboard, text: text, snapshot: snapshot,
                                               ownChangeCount: ownChangeCount)
        guard pasteboard.write(items(for: text, transient: snapshot != nil)) else {
            transaction.restore()
            return nil
        }
        return transaction
    }

    /// Puts the copied contents back, but only if there is a copy and the pasteboard's change count is still the one
    /// this transaction's write produced. Returns whether it did.
    @discardableResult
    public func restore() -> Bool {
        guard let snapshot, pasteboard.changeCount == ownChangeCount else { return false }
        _ = pasteboard.clear()
        return pasteboard.write(snapshot)
    }

    /// The text stays on the clipboard for the user after all, and nothing will be put back. If it was marked
    /// transient it is written again plainly, so clipboard managers keep it.
    ///
    /// Returns whether the text is on the clipboard now. False when someone else has written to the pasteboard
    /// since, which is left alone, or when the system refused the plain copy; then the previous contents are put
    /// back under the same guards as `restore()`, so the user is not left with an empty clipboard.
    public func keepForUser() -> Bool {
        guard pasteboard.changeCount == ownChangeCount else { return false }
        guard let snapshot else { return true }
        let rewrite = pasteboard.clear()
        if pasteboard.write(Self.items(for: text, transient: false)) { return true }
        if pasteboard.changeCount == rewrite {
            _ = pasteboard.clear()
            _ = pasteboard.write(snapshot)
        }
        return false
    }

    /// The text as one pasteboard item, marked transient and auto-generated when it will be taken away again.
    private static func items(for text: String, transient: Bool) -> [PasteboardItemData] {
        var representations = [PasteboardRepresentation(type: textType, data: Data(text.utf8))]
        if transient {
            representations.append(PasteboardRepresentation(type: transientType, data: Data()))
            representations.append(PasteboardRepresentation(type: autoGeneratedType, data: Data()))
        }
        return [PasteboardItemData(representations)]
    }

    /// Every item and type on the pasteboard, or nil when the copy would be incomplete, too large, or the
    /// pasteboard changed while it was read.
    private static func takeSnapshot(of pasteboard: any PasteboardAccess) -> [PasteboardItemData]? {
        let before = pasteboard.changeCount
        let read = pasteboard.readItems(byteLimit: snapshotByteLimit)
        guard pasteboard.changeCount == before, case .items(let items) = read,
              items.reduce(0, { $0 + $1.byteCount }) <= snapshotByteLimit else { return nil }
        return items
    }
}
